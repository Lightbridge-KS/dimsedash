import 'dart:convert';
import 'dart:io';

import 'package:yaml/yaml.dart';

/// Generate diagnostic provenance from manifests and the resolved package source.
Future<void> main(List<String> args) async {
  final manifest = loadYaml(File('pubspec.yaml').readAsStringSync()) as YamlMap;
  final configFile = File('.dart_tool/package_config.json').absolute;
  final config =
      jsonDecode(configFile.readAsStringSync()) as Map<String, dynamic>;
  final net = (config['packages'] as List)
      .cast<Map<String, dynamic>>()
      .singleWhere((p) => p['name'] == 'dartdicom_net');
  final directory = Directory.fromUri(
    configFile.uri.resolve(net['rootUri'] as String),
  );
  final package = loadYaml(
    File('${directory.path}/pubspec.yaml').readAsStringSync(),
  ) as YamlMap;
  final head = await Process.run('git', [
    'rev-parse',
    'HEAD',
  ], workingDirectory: directory.path);
  final dirty = await Process.run('git', [
    'status',
    '--porcelain',
    '--untracked-files=normal',
  ], workingDirectory: directory.path);
  final source = head.exitCode == 0
      ? '${(head.stdout as String).trim()}${(dirty.stdout as String).trim().isEmpty ? '' : '-dirty'}'
      : 'unknown-source';
  final content =
      '// Generated by tools/write_build_versions.dart from the app and resolved library manifests.\n'
      "const appVersion = '${manifest['version']}';\n"
      "const libraryVersion = '${package['version']}@$source';\n";
  final target = File('lib/app/build_versions.dart');
  if (args.contains('--check')) {
    if (!target.existsSync() ||
        target.readAsStringSync().replaceAll(RegExp(r'\s'), '') !=
            content.replaceAll(RegExp(r'\s'), '')) {
      stderr.writeln('Diagnostic versions are stale. Run just versions.');
      exitCode = 1;
    }
  } else {
    target.writeAsStringSync(content);
  }
}
